// CompletionsCmd generates shell completions
type CompletionsCmd struct {
	Bash completionScriptCmd `cmd:"" help:"Generate bash completions"`
	Zsh  completionScriptCmd `cmd:"" help:"Generate zsh completions"`
	Fish completionScriptCmd `cmd:"" help:"Generate fish completions"`
}

type completionScriptCmd struct{}

// Run prints the script for the shell named by the selected command.
func (c *completionScriptCmd) Run(ctx *kong.Context) error {
	_, err := io.WriteString(os.Stdout, completionScripts[ctx.Selected().Name])
	return err
}

// The scripts only hand the command line to nix-tasks, which answers from
// its own CLI model (see Complete), so they never go stale. Results ending in
// "/" are directories and get no trailing space, so a path can be continued.
var completionScripts = map[string]string{
	"bash": `# bash completion for nix-tasks, generated by ` + "`nix-tasks completions bash`" + `

_nix_tasks() {
    local IFS=$'\n'
    COMPREPLY=($(COMP_LINE="$COMP_LINE" COMP_POINT="$COMP_POINT" nix-tasks 2>/dev/null))
    if [[ ${#COMPREPLY[@]} -eq 1 && ${COMPREPLY[0]} == */ ]]; then
        compopt -o nospace 2>/dev/null
    fi
}

complete -F _nix_tasks nix-tasks
`,
	"zsh": `#compdef nix-tasks
# zsh completion for nix-tasks, generated by ` + "`nix-tasks completions zsh`" + `

_nix_tasks() {
    local line="${(j: :)words[1,CURRENT]}"
    local -a matches dirs
    matches=(${(f)"$(COMP_LINE="$line" COMP_POINT=${#line} nix-tasks 2>/dev/null)"})
    dirs=(${(M)matches:#*/})
    matches=(${matches:#*/})
    (( ${#dirs} )) && compadd -S '' -- "${dirs[@]}"
    (( ${#matches} )) && compadd -- "${matches[@]}"
}

if [[ "$funcstack[1]" == _nix[-_]tasks ]]; then
    _nix_tasks "$@"
else
    compdef _nix_tasks nix-tasks
fi
`,
	"fish": `# fish completion for nix-tasks, generated by ` + "`nix-tasks completions fish`" + `

function __nix_tasks_complete
    set -lx COMP_LINE (commandline -cp)
    test -z (commandline -ct)
    and set COMP_LINE "$COMP_LINE "
    nix-tasks 2>/dev/null
end

complete -c nix-tasks -f -a '(__nix_tasks_complete)'
`,
}

// Complete answers a completion request from one of the scripts above (the
// shell sets COMP_LINE) and exits; otherwise it returns and nix-tasks runs
// normally. Arguments and flags tagged completion-predictor:"task", "shell"
// or "dir" complete to the selected flake's task names, its dev shell names,
// or directories.
func Complete(parser *kong.Kong) {
	kongcompletion.Register(parser,
		kongcompletion.WithPredictor("task", complete.PredictFunc(func(complete.Args) []string {
			return listNames(false)
		})),
		kongcompletion.WithPredictor("shell", complete.PredictFunc(func(complete.Args) []string {
			return listNames(true)
		})),
		kongcompletion.WithPredictor("dir", predictDirs()),
	)
}

// predictDirs completes directories. complete.PredictDirs answers "../" with
// "./../x/", which the shell then discards for not matching what was typed.
func predictDirs() complete.Predictor {
	dirs := complete.PredictDirs("*")
	return complete.PredictFunc(func(a complete.Args) []string {
		out := dirs.Predict(a)
		if strings.HasPrefix(a.Last, "..") {
			for i, d := range out {
				out[i] = strings.TrimPrefix(d, "./")
			}
		}
		return out
	})
}

// listNames runs `nix-tasks list --names` for the flake selected on the
// command line being completed. It reads the whole line because the
// predictor only sees the words after the subcommand, and -f usually comes
// before it. Completion must stay quiet, so any failure (no flake, evaluation
// error) yields no names.
func listNames(shells bool) []string {
	self, err := os.Executable()
	if err != nil {
		return nil
	}
	args := []string{"list", "--names"}
	if shells {
		args = append(args, "--shells")
	}
	if flake, ok := flakeArg(strings.Fields(os.Getenv("COMP_LINE"))); ok {
		args = append(args, "-f", flake)
	}

	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, self, args...)
	cmd.Env = slices.DeleteFunc(os.Environ(), func(kv string) bool {
		return strings.HasPrefix(kv, "COMP_LINE=") || strings.HasPrefix(kv, "COMP_POINT=")
	})
	out, err := cmd.Output()
	if err != nil {
		return nil
	}
	return strings.Fields(string(bytes.TrimSpace(out)))
}

// flakeArg returns the value of the last complete -f/--flake on the line.
func flakeArg(words []string) (string, bool) {
	var flake string
	found := false
	for i, w := range words {
		switch {
		case w == "-f" || w == "--flake":
			if i+1 < len(words) {
				flake, found = words[i+1], true
			}
		case strings.HasPrefix(w, "--flake="):
			flake, found = strings.TrimPrefix(w, "--flake="), true
		case strings.HasPrefix(w, "-f="):
			flake, found = strings.TrimPrefix(w, "-f="), true
		}
	}
	if strings.HasPrefix(flake, "~/") {
		if home, err := os.UserHomeDir(); err == nil {
			flake = home + flake[1:]
		}
	}
	return flake, found
}
